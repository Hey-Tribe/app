// Builds the HeyTribe app from app/src into app/index.html plus cached, minified files in app/assets.
//   Edit:  app/src/index.html (page shell), app/src/app.js (code), app/src/app.css (styles)
//   Build: npm run build:app   (needs `npm install` once for esbuild)
// The page shell stays tiny and is re-checked on every visit; code and styles get a content hash in their
// file name, so phones cache them for a year and only download them again after a change.
import { readFileSync, writeFileSync, readdirSync, unlinkSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { transformSync } from "esbuild";

const root = new URL("../", import.meta.url).pathname;
const read = p => readFileSync(root + p, "utf8");
const hash = s => createHash("sha256").update(s).digest("hex").slice(0, 10);

const js = transformSync(read("app/src/app.js"), { loader: "js", minify: true, target: "es2019", legalComments: "none" }).code;
const css = transformSync(read("app/src/app.css"), { loader: "css", minify: true }).code;
const jsName = `app.${hash(js)}.js`, cssName = `app.${hash(css)}.css`;

mkdirSync(root + "app/assets", { recursive: true });
for (const f of readdirSync(root + "app/assets")) if (/^app\.[0-9a-f]{10}\.(js|css)$/.test(f) && f !== jsName && f !== cssName) unlinkSync(root + "app/assets/" + f);
writeFileSync(root + "app/assets/" + jsName, js);
writeFileSync(root + "app/assets/" + cssName, css);

const shell = read("app/src/index.html")
  .replace("<!--APP_CSS-->", `<link rel="stylesheet" href="/app/assets/${cssName}">`)
  .replace("<!--APP_JS-->", `<script src="/app/assets/${jsName}" defer></script>`)
  .replace("<head>", `<head><!-- Generated by tools/build-app.mjs. Edit app/src/ instead. -->`)
  .replace(/<link rel="preload" href="\/assets\/fonts\/atkinson\.woff2"/, `<link rel="preload" href="/app/assets/${jsName}" as="script">\n<link rel="preload" href="/assets/fonts/atkinson.woff2"`);
writeFileSync(root + "app/index.html", shell);

// Tell the offline cache about the new files.
let sw = read("app/sw.js");
sw = sw.replace(/const CACHE = "ht-app-[^"]*";/, `const CACHE = "ht-app-${hash(js + css).slice(0, 8)}";`)
       .replace(/"\/app\/assets\/app\.[0-9a-f]{10}\.js", "\/app\/assets\/app\.[0-9a-f]{10}\.css", /, "")
       .replace('const SHELL = ["/app/", ', `const SHELL = ["/app/", "/app/assets/${jsName}", "/app/assets/${cssName}", `);
writeFileSync(root + "app/sw.js", sw);
console.log(`app/index.html ${shell.length} B · ${jsName} ${js.length} B · ${cssName} ${css.length} B`);
